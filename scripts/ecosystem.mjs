import assert from 'node:assert/strict';
import {readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const repository = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const keys = [
    'id',
    'name',
    'description',
    'role',
    'repository',
    'packages',
    'documentation',
    'family',
    'applications',
];

export function validateCatalog(catalog) {
    assert.deepEqual(Object.keys(catalog).sort(), ['entries', 'schemaVersion']);
    assert.equal(catalog.schemaVersion, 1);
    assert.ok(Array.isArray(catalog.entries) && catalog.entries.length > 0);

    const ids = new Set();
    const packages = new Set();

    for (const entry of catalog.entries) {
        assert.deepEqual(Object.keys(entry).sort(), [...keys].sort(), 'Only stable catalog fields are allowed');

        for (const key of [
            'id',
            'name',
            'description',
            'role',
            'repository',
            'documentation',
            'family',
        ]) {
            assert.equal(typeof entry[key], 'string');
            assert.ok(entry[key].length > 0 && entry[key].length <= 500 && !/[\r\n|<>]/.test(entry[key]));
        }

        assert.match(entry.id, /^[a-z][a-z0-9-]*$/);
        assert.ok(!ids.has(entry.id), 'Duplicate catalog id');
        ids.add(entry.id);
        assert.ok(['portline', 'dockline'].includes(entry.family));
        assert.match(entry.repository, /^https:\/\/github\.com\/[A-Za-z0-9_-]+\/[A-Za-z0-9_.-]+$/);

        const documentation = new URL(entry.documentation);

        assert.equal(documentation.protocol, 'https:');
        assert.ok(!documentation.username && !documentation.password);
        assert.ok(Array.isArray(entry.applications) && entry.applications.every(name =>
            typeof name === 'string' && name.length > 0 && !/[\r\n|<>]/.test(name)));
        assert.ok(Array.isArray(entry.packages) && entry.packages.length > 0);

        for (const name of entry.packages) {
            assert.match(name, /^@[a-z0-9-]+\/[a-z0-9-]+$/);
            assert.ok(!packages.has(name), 'An npm package must have one catalog entry');
            packages.add(name);
        }
    }

    return catalog.entries;
}

export function renderCatalog(catalog) {
    const entries = [...validateCatalog(catalog)].sort((left, right) => left.id.localeCompare(right.id, 'en'));
    const applications = entries.filter(entry => entry.family === 'portline' && entry.applications.length);
    const related = entries.filter(entry => entry.family === 'dockline');
    const shared = entries.filter(entry => entry.family === 'portline' && !entry.applications.length);
    const entryLines = (entry, application = false) => [
        '## ' + entry.name,
        '',
        entry.description,
        '',
        ...(application ? ['[API documentation](' + entry.documentation + 'api/) · [CLI documentation](' + entry.documentation + 'cli/) · [GitHub](' + entry.repository + ')', ''] : []),
        'Packages: ' + entry.packages.map(name => '[`' + name + '`](https://www.npmjs.com/package/' + name + ')').join(', ') + '.',
        '',
        ...(application ? [] : ['[Documentation](' + (entry.id === 'portline' ? '/integration/' : entry.documentation) + ') · [GitHub](' + entry.repository + ')', '']),
    ];
    const generated = '<!-- Generated by scripts/ecosystem.mjs from ecosystem.json. Do not edit this file. -->';
    const libraries = [
        generated,
        '# Application libraries',
        '',
        'Choose the application that owns the saved settings. Follow its API documentation for code or its CLI documentation for terminal commands.',
        '',
        'Compare [storage, discovery, credentials and write support](/libraries/compare), or start with [cross-application workflows](/workflows/).',
        '',
        ...applications.flatMap(entry => entryLines(entry, true)),
        '## Transfers, SSH and keys',
        '',
        'Use [related tools](/libraries/related) for Dockline operations and independent key conversion. Shared contracts and CLI embedding are documented under [Build an integration](/integration/).',
        '',
    ].join('\n');
    const markdown = [
        generated,
        '# Connection library ecosystem',
        '',
        'Portline is the saved-connection library family. Start with an application below. Dockline supplies related transport and key tools; the shared packages support integration authors.',
        '',
        ...applications.flatMap(entry => entryLines(entry, true)),
        '# Related Dockline tools',
        '',
        'See [related tools](/libraries/related) to choose transfers, SSH or key conversion.',
        '',
        ...related.flatMap(entry => entryLines(entry)),
        '# Shared integration infrastructure',
        '',
        ...shared.flatMap(entry => entryLines(entry)),
        'Directory contributions are described in [contributing](/integration/contributing).',
        '',
    ].join('\n');

    return {markdown, libraries};
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const catalog = JSON.parse(await readFile(path.join(repository, 'ecosystem.json'), 'utf8'));
    const {markdown, libraries} = renderCatalog(catalog);
    const filename = path.join(repository, 'docs/ecosystem.md');
    const libraryFile = path.join(repository, 'docs/libraries/index.md');

    if (process.argv.includes('--check')) {
        assert.equal(await readFile(filename, 'utf8'), markdown, 'Generated index drifted; run npm run docs:build');
        assert.equal(await readFile(libraryFile, 'utf8'), libraries, 'Library directory drifted; run npm run docs:build');
        console.log('Catalog validated; ecosystem and library directories match their source.');
    } else {
        await writeFile(filename, markdown);
        await writeFile(libraryFile, libraries);
        console.log('Generated ecosystem Markdown from ecosystem.json.');
    }
}
